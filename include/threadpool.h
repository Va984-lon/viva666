/* ============================================================================
 * threadpool.h — пул рабочих потоков (многопоточный фундамент проекта)
 *
 * Индивидуальность: вместо "ручного" создания N потоков под каждую задачу
 * реализован классический пул с очередью задач (producer/consumer на mutex +
 * двух condvar). Анализатор отдаёт в пул задачи парсинга чанков файла и
 * агрегации, симулятор — задачи генерации продаж. Один механизм — обе
 * программы (принцип повторного использования).
 * ==========================================================================*/
#ifndef VEKTRA_THREADPOOL_H
#define VEKTRA_THREADPOOL_H

typedef void (*tp_task_fn)(void *arg);

typedef struct tp_pool tp_pool_t;

/* Создаёт пул из nworkers потоков. */
tp_pool_t *tp_create(size_t nworkers);
/* Ставит задачу в очередь (не блокируется надолго). */
int        tp_submit(tp_pool_t *p, tp_task_fn fn, void *arg);
/* Блокируется до выполнения всех принятых задач. */
void       tp_drain(tp_pool_t *p);
/* Останавливает пул (предварительно drain). */
void       tp_destroy(tp_pool_t *p);

#endif /* VEKTRA_THREADPOOL_H */
